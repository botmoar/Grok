def clean_html(raw: str) -> str:
    text = raw or ""
    text = re.sub(r'\sdata-(?:start|end|section-id|id)="[^"]*"', "", text)
    text = re.sub(r"</?h1\b", lambda m: m.group(0).replace("h1", "h2"), text)
    text = re.sub(r"<p>(?:\s|&nbsp;|<br\s*/?>)*</p>", "", text, flags=re.I)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def plain(raw: str) -> str:
    t = re.sub(r"<[^>]+>", " ", raw or "")
    t = html.unescape(t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def meta_from(title: str, body: str) -> str:
    base = plain(body)
    base = re.sub(r"^(הערה לעדכון:)?", "", base).strip()
    if len(base) > 150:
        cut = base[:150]
        sp = cut.rfind(" ")
        base = (cut[:sp] if sp > 80 else cut).rstrip(".,") + "…"
    if title and title not in base:
        return base
    return base


