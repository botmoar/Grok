def _esc(text: str) -> str:
    """Escape plain text; strings that already carry links pass through."""
    return text if "<a " in text else html.escape(text, quote=False)


def render(topic: dict) -> str:
    parts = [f"<p>{_esc(p)}</p>" for p in topic["intro"]]
    parts.append("<h2>למי זה מתאים</h2>")
    parts.append('<ul class="am-checklist">' + "".join(f"<li>{_esc(w)}</li>" for w in topic["who"]) + "</ul>")
    parts.append(f"<h2>{topic['problems_title']}</h2>")
    parts.append('<ul class="am-points">' + "".join(
        f"<li><strong>{_esc(t)}</strong>{_esc(d)}</li>" for t, d in topic["problems"]) + "</ul>")
    parts.append("<h2>איך אני מלווה, צעד אחר צעד</h2>")
    parts.append('<ol class="am-steps">' + "".join(
        f"<li><strong>{_esc(t)}.</strong> {_esc(d)}</li>" for t, d in topic["steps"]) + "</ol>")
    if topic.get("quote"):
        text, slug, name = topic["quote"]
        parts.append(f'<blockquote><p>{_esc(text)}</p><p>{link(slug, name)}</p></blockquote>')
    if topic.get("extra"):
        parts.append(topic["extra"])
    parts.append("<h2>מה להכין לפגישה</h2>")
    parts.append('<ul class="am-prep">' + "".join(f"<li>{_esc(p)}</li>" for p in topic["prepare"]) + "</ul>")
    return "\n".join(parts)


def posts() -> list:
    out = []
    for topic in TOPICS:
        out.append({
            "slug": topic["slug"],
            "title": topic["title"],
            "date": DATE,
            "categories": [CATEGORY],
            "content": render(topic),
            "excerpt": topic["excerpt"],
            "seo_title": topic["seo_title"],
            "meta_desc": topic["meta_desc"],
            "faq": [{"q": q, "a": a} for q, a in topic["faq"]],
            "related": topic["related"],
            "action": "mortgage-topic",
            "featured_image": "",
        })
    return out
